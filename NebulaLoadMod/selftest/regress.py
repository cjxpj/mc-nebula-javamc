def log_text() -> str:
    path = log_path()
    return path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""


def check_docs_site():
    """开服副作用：jar 内文档被铺到 <gameDir>/nebula/_docs，且不参与词库加载。

    只验「文件落地且内容一致」——文档是拿来给人看的，编译器根本不该看到它。
    """
    target = TEST / "nebula" / "_docs"
    index = target / "index.html"
    stamp = target / ".stamp"
    if not index.is_file():
        raise RuntimeError(f"文档站点未生成：{index}")
    if not stamp.is_file():
        raise RuntimeError(f"文档站点缺少指纹文件：{stamp}")
    inner = hashlib.sha256(index.read_bytes()).hexdigest()
    outer = hashlib.sha256((DOCS / "index.html").read_bytes()).hexdigest()
    if inner != outer:
        raise RuntimeError(
            f"nebula/_docs/index.html 与 NebulaLoadMod/docs 内容不一致（{inner[:12]} vs {outer[:12]}）")
    files = [p for p in target.rglob("*") if p.is_file()]
    version_file = target / "version.txt"
    if not version_file.is_file():
        raise RuntimeError(f"文档站点缺少版本文件：{version_file}")
    site_version = version_file.read_text(encoding="utf-8").strip()
    if site_version != mod_version():
        raise RuntimeError(
            f"_docs/version.txt 是 {site_version}，模组版本是 {mod_version()}")
    for line in log_text().splitlines():
        # 我们自己的「离线文档站点已生成」也带 _docs，别把它当成引擎报错。
        if "[星云]" in line and "_docs" in line and "离线文档站点" not in line:
            raise RuntimeError(f"文档目录被引擎当成插件处理了：{line.strip()}")
    log(f"[PASS] 离线文档站点：_docs/index.html 与 NebulaLoadMod/docs 一致，{len(files)} 个文件，"
        f"版本 {site_version}，stamp {stamp.read_text(encoding='utf-8').strip()[:12]}…")


def run_checks():
    checks = json.loads((HERE / "checks.json").read_text(encoding="utf-8"))
    passed = 0
    for item in checks:
        if "log" in item:
            # 日志断言：词库 `$世界.执行命令 say …$` 的回显落在 latest.log 里。
            # 事件类行为（治疗 / 每秒心跳）没有可直接反查的世界状态，只能看日志。
            lines = [line.strip() for line in log_text().splitlines() if item["log"] in line]
            matched = [line for line in lines if item.get("contains", "") in line]
            out = " | ".join(matched or lines)
            ok = len(matched) == item["count"] if "count" in item else bool(matched)
        else:
            try:
                out = rcon(item["cmd"]).strip().replace("\n", " | ")
            except (OSError, RuntimeError) as exc:
                out = f"RCON ERROR {exc}"
            if item.get("expect") == "test_passed":
                ok = "Test passed" in out
            else:
                ok = item.get("contains", "") in out
                # 负向断言：抓「关键字恰好在，但格式根本不对」的假 PASS。
                # 例：text 写成 JSON 字符串时，data get 里同样含「暴击」/「gold」，
                # 但整串其实是纯文本组件，客户端会把 JSON 原文画出来。
                if ok and item.get("not_contains"):
                    ok = item["not_contains"] not in out
        passed += int(ok)
        log(f"[{'PASS' if ok else 'FAIL'}] {item['name']}: {out[:180]}")
    return passed, len(checks)


def readback():
    lines = log_text().splitlines()
    log("\n=== 词库读回 ===")
    for line in lines:
        if "REGRESS-" in line:
            log(line.strip())
    warns = [line for line in lines if "[星云]" in line and "WARN" in line]
    log(f"=== 宿主告警（{len(warns)} 条）===")
    for line in warns[-10:]:
        log(line.strip())
    return len(warns)


def main():
    parser = argparse.ArgumentParser(description="星云 mc 回归自检")
    parser.add_argument("--keep", action="store_true", help="保留 .testserver 目录")
    parser.add_argument("--verify-only", action="store_true",
                        help="只校验产物与源码一致性，不启动服务端")
    parser.add_argument("--skip-verify", action="store_true",
                        help="跳过产物校验（不推荐，可能用旧 jar 得出假 PASS）")
    parser.add_argument("--server-dir", default=None,
                        help="目标 MC 版本的 server 目录（默认 javamc/server-1.21.11，即 1.21.11）")
    parser.add_argument("--test-dir", default=None,
                        help="隔离测试服目录（默认按 server 目录派生，各版本互不干扰）")
    args = parser.parse_args()
    configure_paths(args.server_dir, args.test_dir)

    if args.skip_verify:
        log("[校验] 已跳过（--skip-verify）")
    else:
        verify_artifacts()
    if args.verify_only:
        return

    for path in (JAR, JDK, WIN_ARGS):
        if not path.exists():
            raise RuntimeError(f"缺少构建产物：{path}")

    server_proc = None
    bots = []
    try:
        prepare()
        server_proc = start_server()
        wait_ready(server_proc)
        wait_rcon()

        # 开服第一件事就是铺文档站点，先验它，后面的断言才有意义。
        check_docs_site()

        # 固定加载 (0,0) 区块，方块类动作才能落地（spawn 位置随世界生成变化）。
        rcon("forceload add 0 0")
        bots.append(start_bot("SelfBot"))
        bots.append(start_bot("SelfBot2", active=False))
        wait_players(["SelfBot", "SelfBot2"])

        # bot 进服 1.5s 后发 /自检；动作延迟落地，重新 load 触发 [f]初始化 里的在线读回。
        time.sleep(4)
        log("[自检] " + rcon("nebula load 自检").strip())

        log("\n=== 原版命令反查 ===")
        passed, total = run_checks()
        warns = readback()

        log(f"\n=== 结果：{passed}/{total} PASS，宿主告警 {warns} 条 ===")
        if passed != total:
            raise RuntimeError(f"有 {total - passed} 项反查失败")
    finally:
        log("\n[收尾] 恢复 tick 并优雅停服")
        try:
            rcon("tick unfreeze")
            rcon("tick rate 20")
            rcon("stop")
        except (OSError, RuntimeError):
            pass
        if server_proc is not None:
            try:
                server_proc.wait(timeout=60)
            except subprocess.TimeoutExpired:
                server_proc.terminate()
        for bot in bots:
            if bot.poll() is None:
                bot.terminate()
        if args.keep:
            log(f"[收尾] 保留测试服：{TEST}（libraries/.jdk 仍是联接，勿直接 rmtree）")
        else:
            cleanup()
            log("[收尾] 隔离测试服已清理，线上 libraries/.jdk/world 完好")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        log(f"回归失败：{exc}")
        sys.exit(1)
