def log(text):
    print(text, flush=True)


def fingerprint(root, pattern):
    """相对路径 -> 内容 SHA256（大写，与 PowerShell Get-FileHash 输出一致）。"""
    out = {}
    for path in sorted(root.rglob(pattern)):
        if path.is_file():
            out[path.relative_to(root).as_posix()] = (
                hashlib.sha256(path.read_bytes()).hexdigest().upper())
    return out


def mod_version():
    """版本号唯一来源：NeoForge 自己读的那份模组元数据（build.ps1 同样从它派生）。"""
    match = re.search(r'^version="([^"]*)"', MODS_TOML.read_text(encoding="utf-8"), re.M)
    if not match:
        raise RuntimeError(f"读不到 version=：{MODS_TOML}")
    return match.group(1)


def configure_paths(server_dir=None, test_dir=None):
    """按目标 MC 版本的 server 目录重算全部运行期路径。

    每个版本各自持有 libraries/.jdk/mods/world，测试服目录也按版本派生，
    避免两套回归互相清掉对方的现场。默认跟随主线的 1.21.11 目录。
    """
    global SERVER, TEST, JAR, JDK, WIN_ARGS, MC_VERSION, MC_VERSION
    SERVER = pathlib.Path(server_dir).resolve() if server_dir else ROOT / "server-1.21.11"
    found = re.search(r"1\.21\.\d+", SERVER.name)
    MC_VERSION = found.group(0) if found else "1.21.11"
    if test_dir:
        TEST = pathlib.Path(test_dir).resolve()
    else:
        suffix = SERVER.name[7:] if SERVER.name.startswith("server-") else SERVER.name
        TEST = ROOT / (".testserver-" + suffix)
    JAR = SERVER / "mods" / f"nebula-neoforge-bridge-{mod_version()}.jar"

    jdk_candidates = sorted((SERVER / ".jdk").glob("jdk-*"))
    JDK = (jdk_candidates[-1] / "bin" / "java.exe") if jdk_candidates else (
        SERVER / ".jdk" / "jdk-21.0.12.1-win32-x86_64" / "bin" / "java.exe")

