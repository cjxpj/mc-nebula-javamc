def docs_fingerprint():
    """离线文档站点的内容指纹（md + html），与 build.ps1 的 docs 字段同源。"""
    out = {}
    for path in sorted(DOCS.rglob("*")):
        if path.is_file() and path.suffix in (".md", ".html"):
            out[path.relative_to(DOCS).as_posix()] = (
                hashlib.sha256(path.read_bytes()).hexdigest().upper())
    return out


def embedded_sources(dll_bytes):
    """从 dll 的 .rodata 解析 build.rs 在编译时写入的源码指纹。"""
    match = EMBEDDED_RE.search(dll_bytes)
    if not match:
        return None
    out = {}
    for pair in match.group(1).decode("ascii").split(";"):
        if ":" in pair:
            key, value = pair.split(":", 1)
            out[key] = value.upper()
    return out


def diff_fingerprint(label, expected, current):
    """比对构建时记录的指纹与工作区现状，报出具体变动的文件。"""
    if expected is None:
        return [f"{label} 指纹缺失：jar 未记录对应源码，请跑一次全量构建"]
    diffs = []
    for key in sorted(set(expected) | set(current)):
        if key not in current:
            diffs.append(f"{label} {key}：构建后源码被删除")
        elif key not in expected:
            diffs.append(f"{label} {key}：构建后新增源码")
        elif str(expected[key]).upper() != current[key]:
            diffs.append(f"{label} {key}：内容已改动（产物需要重建）")
    return diffs


def verify_artifacts():
    """确认 jar 由当前源码构建：按内容指纹判断，不用 mtime（空保存会误报）。"""
    problems = []
    if not JAR.exists():
        problems.append(f"缺少 jar：{JAR}")
    if not RELEASE_DLL.exists():
        problems.append(f"缺少 release 原生库：{RELEASE_DLL}（先跑全量构建）")

    if not problems:
        inner = None
        manifest = None
        embedded = None
        docs_entry = None
        stamp_entry = None
        jar_version = None
        events_entry = None
        specs_entry = None
        with zipfile.ZipFile(JAR) as z:
            names = z.namelist()
            if "nebula/events.json" in names:
                events_entry = z.read("nebula/events.json")
            if "nebula/world-specs.json" in names:
                specs_entry = z.read("nebula/world-specs.json")
            if "docs/index.html" in names:
                docs_entry = z.read("docs/index.html")
            if "docs/.stamp" in names:
                stamp_entry = z.read("docs/.stamp").decode("utf-8-sig").strip()
            if "docs/version.txt" in names:
                jar_version = z.read("docs/version.txt").decode("utf-8-sig").strip()
            if NATIVE_ENTRY not in names:
                problems.append(f"jar 内缺少 {NATIVE_ENTRY}")
            else:
                dll_bytes = z.read(NATIVE_ENTRY)
                inner = hashlib.sha256(dll_bytes).hexdigest()
                embedded = embedded_sources(dll_bytes)
                src = hashlib.sha256(RELEASE_DLL.read_bytes()).hexdigest()
                if inner != src:
                    problems.append(
                        f"jar 内 dll 与 release dll 哈希不一致（{inner[:12]} vs {src[:12]}）")
                else:
                    log(f"[校验] 内嵌 dll SHA256 {inner[:12]}… 与 release 一致")
            if MANIFEST_ENTRY in names:
                manifest = json.loads(z.read(MANIFEST_ENTRY).decode("utf-8-sig"))

        if manifest:
            log(f"[校验] 构建指纹 {manifest.get('builtAt', '?')}"
                + ("（SkipRust，指纹来自原生库清单）" if manifest.get("skipRust") else ""))
            rust_now = fingerprint(RUST_SRC, "*.rs")
            java_now = fingerprint(JAVA_SRC, "*.java")
            problems += diff_fingerprint("Rust", manifest.get("rust"), rust_now)
            problems += diff_fingerprint("Java", manifest.get("java"), java_now)
            # 离线文档站点也是产物的一部分：jar 里的文档比 NebulaLoadMod/docs 旧，服主看到的
            # 就是过期的站点（比如改完 plugin-guide 忘了重建），所以同样按内容比对。
            docs_now = docs_fingerprint()
            problems += diff_fingerprint("文档", manifest.get("docs"), docs_now)
            # 通用事件桥的清单也是产物的一部分：jar 里旧清单会让新事件订阅不到。
            events_src = MOD / "src" / "main" / "resources" / "nebula" / "events.json"
            if events_entry is None:
                problems.append("jar 内缺少 nebula/events.json：通用事件桥不可用")
            elif not events_src.exists():
                problems.append("缺少事件清单源码：请跑 python NebulaLoadMod/tools/gen_events.py")
            elif hashlib.sha256(events_entry).digest() != hashlib.sha256(
                    events_src.read_bytes()).digest():
                problems.append("jar 内 nebula/events.json 与源码不一致：重新生成清单后全量构建")
            # 中文事件名是清单的一部分：旧清单会让 [事件]右键物品 被当成「查不到」跳过。
            if events_entry is not None:
                try:
                    cn_names = json.loads(events_entry.decode("utf-8-sig")).get("cnNames", {})
                except (ValueError, UnicodeDecodeError) as exc:
                    cn_names = {}
                    problems.append(f"jar 内事件清单无法解析：{exc}")
                for zh, en in {
                    "右键物品": "PlayerInteractEvent.RightClickItem",
                    "右键方块": "PlayerInteractEvent.RightClickBlock",
                    "右键空气": "PlayerInteractEvent.RightClickEmpty",
                    "左键方块": "PlayerInteractEvent.LeftClickBlock",
                    "左键空气": "PlayerInteractEvent.LeftClickEmpty",
                    "右键实体": "PlayerInteractEvent.EntityInteract",
                    "右键实体部位": "PlayerInteractEvent.EntityInteractSpecific",
                    "玩家退出": "PlayerEvent.PlayerLoggedOutEvent",
                }.items():
                    if cn_names.get(zh) != en:
                        problems.append(f"事件清单缺少中文别名 {zh} → {en}")
            # 世界 方法规格是 jar 内的运行时输入：旧 jar 会让新规格不生效。
            specs_src = MOD / "src" / "main" / "resources" / "nebula" / "world-specs.json"
            if specs_entry is None:
                problems.append("jar 内缺少 nebula/world-specs.json：世界 方法规格不可用")
            elif not specs_src.exists():
                problems.append("缺少 world-specs.json 源码")
            elif hashlib.sha256(specs_entry).digest() != hashlib.sha256(
                    specs_src.read_bytes()).digest():
                problems.append("jar 内 nebula/world-specs.json 与源码不一致：请重新构建")
            if specs_src.exists():
                specs_hash = hashlib.sha256(specs_src.read_bytes()).hexdigest().upper()
                if str(manifest.get("worldSpecs", "")).upper() != specs_hash:
                    problems.append("manifest 的 worldSpecs 指纹与源码不一致：请重新构建")
            if stamp_entry is None:
                problems.append("jar 内缺少 docs/.stamp：文档站点无法判断是否需要重建")
            elif str(manifest.get("docsStamp", "")).lower() != stamp_entry.lower():
                problems.append("jar 内 docs/.stamp 与构建记录不一致")
            if docs_entry is None:
                problems.append("jar 内缺少 docs/index.html")
            elif hashlib.sha256(docs_entry).digest() != hashlib.sha256(
                    (DOCS / "index.html").read_bytes()).digest():
                problems.append("jar 内 docs/index.html 与 NebulaLoadMod/docs 内容不一致")

            # 版本号只有一个来源（mods.toml）：jar 名、jar 内 version.txt、manifest
            # 三处必须都等于它，否则就是「改了版本没重建」。
            expected_version = mod_version()
            if str(manifest.get("version", "")) != expected_version:
                problems.append(
                    f"jar 记录的模组版本 {manifest.get('version')} 与 neoforge.mods.toml 的 "
                    f"{expected_version} 不一致：请重新构建")
            if jar_version is None:
                problems.append("jar 内缺少 docs/version.txt")
            elif jar_version != expected_version:
                problems.append(
                    f"jar 内 docs/version.txt 是 {jar_version}，应为 {expected_version}")

            cargo_expected = manifest.get("cargoToml")
            cargo_now = hashlib.sha256((BRIDGE / "Cargo.toml").read_bytes()).hexdigest().upper()
            if not cargo_expected:
                problems.append("Cargo.toml 指纹缺失：请跑一次全量构建")
            elif str(cargo_expected).upper() != cargo_now:
                problems.append("Cargo.toml 内容已改动：产物需要重建")

            if inner and str(manifest.get("dllSha256", "")).upper() != inner.upper():
                problems.append("manifest 记录的 dll 哈希与 jar 内实际 dll 不一致")

            # 信任链终点：dll 自己在编译时写下的源码指纹，不依赖任何事后文件。
            if embedded is None:
                problems.append("dll 内缺少编译期源码指纹：请用新版 build.ps1 全量构建")
            else:
                expected_rust = fingerprint(RUST_SRC, "*.rs")
                expected_rust["Cargo.toml"] = hashlib.sha256(
                    (BRIDGE / "Cargo.toml").read_bytes()).hexdigest().upper()
                problems += diff_fingerprint("dll 内嵌", embedded, expected_rust)
                if manifest.get("embeddedSources"):
                    recorded = embedded_sources(
                        b"NEBULA_SOURCES="
                        + manifest["embeddedSources"].encode("ascii") + b"\x00")
                    if recorded != embedded:
                        problems.append("jar manifest 记录的内嵌指纹与 dll 实际内容不一致")
                if not problems:
                    log("[校验] dll 编译期指纹与当前源码一致（一手证据）")

            # 一手证据：cargo 产出 dll 时落下的清单，与 dll 哈希绑定。
            # 存在时交叉校验，避免 jar 里的 rust 指纹只是「上一个 jar 的转述」。
            if NATIVE_MANIFEST.exists():
                nm = json.loads(NATIVE_MANIFEST.read_text(encoding="utf-8-sig"))
                if str(nm.get("dllSha256", "")).upper() != (inner or "").upper():
                    problems.append("原生库清单的 dll 哈希与 jar 内 dll 不一致：dll 可能被替换，请跑全量构建")
                if nm.get("rust") and dict(nm["rust"]) != dict(manifest.get("rust") or {}):
                    problems.append("jar 的 Rust 指纹与原生库清单不一致：指纹来源可疑")
                if nm.get("embeddedSources"):
                    recorded = embedded_sources(
                        b"NEBULA_SOURCES="
                        + nm["embeddedSources"].encode("ascii") + b"\x00")
                    if recorded != embedded:
                        problems.append("原生库清单记录的内嵌指纹与实际 dll 不一致")
                if not problems:
                    log("[校验] 原生库清单交叉校验通过")
            else:
                log("[校验] ! 未找到原生库清单（可能用了 -RustTargetDir），跳过交叉校验")

            if not problems:
                log(f"[校验] 源码内容指纹一致（Rust {len(rust_now)} / Java {len(java_now)} 个文件，"
                    f"文档 {len(docs_now)} 个文件）")
        else:
            # 只有没有 manifest 的旧 jar 才退回时间戳启发式。
            log("[校验] ! jar 内无构建指纹（旧产物），退回 mtime 启发式；建议跑一次全量构建")
            rust_files = list(RUST_SRC.rglob("*.rs"))
            if rust_files and max(p.stat().st_mtime for p in rust_files) > RELEASE_DLL.stat().st_mtime + 1:
                problems.append("Rust 源码比 release dll 新：可能用了 -SkipRust 打包旧产物")
            java_files = list(JAVA_SRC.rglob("*.java"))
            if java_files and max(p.stat().st_mtime for p in java_files) > JAR.stat().st_mtime + 1:
                problems.append("Java 源码比 jar 新：jar 可能是旧构建")

    if problems:
        for item in problems:
            log("[校验] x " + item)
        raise RuntimeError(
            "产物校验未通过；先跑 powershell -ExecutionPolicy Bypass -File NebulaLoadMod/build.ps1")
    log("[校验] 产物与源码一致")


def remove_junctions():
    """先摘掉目录联接，绝不能让 rmtree 顺着联接删掉线上 libraries/.jdk。"""
    for name in ("libraries", ".jdk"):
        link = TEST / name
        if link.exists():
            # cmd 在中文 Windows 上输出 GBK，不要按 utf-8 解码（会产生线程里的
            # UnicodeDecodeError 噪音）；这里只关心 returncode，输出留成 bytes。
            subprocess.run(["cmd", "/c", "rmdir", str(link)], capture_output=True)


def cleanup():
    if not TEST.exists():
        return
    remove_junctions()
    shutil.rmtree(TEST, ignore_errors=True)
    for rel in ("libraries", ".jdk", "world"):
        if not (SERVER / rel).exists():
            raise RuntimeError(f"清理后线上目录缺失：{SERVER / rel}")


def prepare():
    cleanup()
    TEST.mkdir(parents=True)
    for name in ("libraries", ".jdk"):
        result = subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(TEST / name), str(SERVER / name)],
            capture_output=True)
        if result.returncode != 0:
            detail = result.stderr.decode("utf-8", "replace").strip() if result.stderr else ""
            raise RuntimeError(f"创建目录联接失败 {name}: {detail}")

    for folder in ("mods", "logs", "bot", "nebula/自检", "config"):
        (TEST / folder).mkdir(parents=True, exist_ok=True)
    shutil.copy2(JAR, TEST / "mods" / JAR.name)
    shutil.copy2(SERVER / "eula.txt", TEST / "eula.txt")
    (TEST / "server.properties").write_text(PROPERTIES, encoding="utf-8")
    (TEST / "user_jvm_args.txt").write_text("-Xmx1500M\n-Xms512M\n", encoding="utf-8")

    wordlib = TEST / "nebula" / "自检"
    shutil.copy2(HERE / "wordlib" / "main.n", wordlib / "main.n")
    shutil.copy2(HERE / "wordlib" / "nebula.ini", wordlib / "nebula.ini")
    shutil.copy2(HERE / "bot.js", TEST / "bot" / "bot.js")

    # Prefer the already-installed tree in NebulaLoadMod/selftest/node_modules via NODE_PATH.
    # A fresh per-version test dir would otherwise need npm + network every run.
    shared_modules = HERE / "node_modules"
    if (TEST / "bot" / "node_modules" / "mineflayer").exists():
        log("[准备] 复用隔离服已有的 mineflayer")
    elif (shared_modules / "mineflayer").exists():
        log("[准备] 复用 NebulaLoadMod/selftest/node_modules（NODE_PATH，离线可用）")
    else:
        log("[准备] 安装 mineflayer（仅首次）…")
        subprocess.run(
            ["cmd", "/c", "npm", "install", "mineflayer@4.39.0",
             "--no-audit", "--no-fund"],
            cwd=str(TEST / "bot"), check=True, capture_output=True)
    log("[准备] 隔离测试服已就绪")


def log_path():
    return TEST / "logs" / "latest.log"


def wait_ready(proc, timeout=150):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if proc.poll() is not None:
            raise RuntimeError("服务端进程提前退出")
        path = log_path()
        if path.exists() and "Done (" in path.read_text(encoding="utf-8", errors="replace"):
            log("[启动] 服务端 Done，RCON 就绪")
            return
        time.sleep(1)
    raise RuntimeError("服务端启动超时")


def wait_rcon(timeout=30):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            rcon("list")
            return
        except (OSError, RuntimeError):
            time.sleep(1)
    raise RuntimeError("RCON 连接超时")


def wait_players(names, timeout=60):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            out = rcon("list")
            if all(name in out for name in names):
                log("[玩家] " + out.strip())
                return
        except (OSError, RuntimeError):
            pass
        time.sleep(1)
    raise RuntimeError(f"假玩家未全部进服：{names}")


